"""
Experimental software ISO14443-B reader for the Chameleon Ultra.

The Ultra's RC522-compatible front-end (Ci522) has no ISO14443-B framing. This
module works around it entirely in software, on top of the experimental
HF14B_BITBANG firmware command:

* TX: the PCD->PICC frame (SOF, 10-bit characters, EOF, NRZ-L, ~10% ASK) is
  generated by rewriting CWGsPReg once per SPI byte in a single DMA burst.
* RX: the RC522 receiver cannot decode BPSK, but its TestADCReg exposes the
  I/Q ADC. Sampled at ~1 MS/s, the 847.5 kHz subcarrier aliases to ~150 kHz;
  we estimate that frequency (squaring removes the BPSK), mix down, low-pass,
  take the phase against TR1 (logic 1), find SOF and slice bits at 1 etu.
  Every frame is accepted only if its CRC_B is valid.
"""
import cmath
import math
import time

US_PER_SAMPLE = 1.0025                      # measured SPIM byte period on nRF52840 @ 8 MHz
ETU_SAMPLES = 128 / 13.56 / US_PER_SAMPLE   # ~9.42 samples per etu
ETU_Q8 = round(ETU_SAMPLES * 256)
ST25TB_MOD = dict(mod_reg=0x28, hi=0x3F, lo=0x09)   # CWGsPReg 0x3F -> 0x09 gives a usable ASK depth

# Modulation settings that produced valid ST25TB answers, most reliable first.
# Tried in order when the tag does not answer INITIATE (other distances/positions).
MOD_CANDIDATES = [
    ST25TB_MOD,
    dict(mod_reg=0x28, hi=0x3F, lo=0x06),
    dict(mod_reg=0x28, hi=0x3F, lo=0x0C),
    dict(mod_reg=0x28, hi=0x3F, lo=0x03),
    dict(mod_reg=0x28, hi=0x3F, lo=0x0F),
    dict(mod_reg=0x28, hi=0x3F, lo=0x12),
    dict(mod_reg=0x27, hi=0xF4, lo=0x44),   # GsNReg
    dict(mod_reg=0x27, hi=0xF4, lo=0x24),
    dict(mod_reg=0x14, hi=0x83, lo=0x82),   # TxControlReg: one TX driver off
    dict(mod_reg=0x14, hi=0x83, lo=0x81),
]


def crc_14b(data) -> bytes:
    """CRC_B (ISO/IEC 13239, CRC-16/X-25), returned LSB first as sent on air."""
    crc = 0xFFFF
    for b in data:
        crc ^= b
        for _ in range(8):
            crc = (crc >> 1) ^ 0x8408 if crc & 1 else crc >> 1
    crc = ~crc & 0xFFFF
    return bytes([crc & 0xFF, crc >> 8])


def crc_ok(frame) -> bool:
    return len(frame) >= 3 and crc_14b(frame[:-2]) == frame[-2:]


def _sx(v):
    return v - 16 if v > 7 else v


def _channel(samples, ch):
    return [_sx(x >> 4) if ch == "I" else _sx(x & 15) for x in samples]


def _active_span(sig, thr=1.5, win=12):
    rms = []
    for i in range(len(sig)):
        seg = sig[max(0, i - win // 2):i + win // 2]
        m = sum(seg) / len(seg)
        rms.append(math.sqrt(sum((x - m) ** 2 for x in seg) / len(seg)))
    on = [i for i, r in enumerate(rms) if r > thr]
    return (on[0], on[-1]) if on else None


def _estimate_freq(seg):
    def score(f):
        return abs(sum((x * x) * cmath.exp(-2j * 2 * math.pi * f * n) for n, x in enumerate(seg)))

    best_f, best_s = 0.0, -1.0
    f = 0.10
    while f < 0.20:
        s = score(f)
        if s > best_s:
            best_f, best_s = f, s
        f += 0.0005
    for f in [best_f + k * 0.00002 for k in range(-25, 26)]:
        s = score(f)
        if s > best_s:
            best_f, best_s = f, s
    return best_f


def bpsk_decode(samples, ch="Q", thr=1.5):
    """Decode one ISO14443-B PICC frame from TestADCReg samples. Returns bytes (incl. CRC) or None."""
    sig = _channel(samples, ch)
    span = _active_span(sig, thr=thr)
    if span is None:
        return None
    a, b = span[0] + 2, span[1]
    seg = sig[a:b]
    if len(seg) < 20 * ETU_SAMPLES:
        return None
    m = sum(seg) / len(seg)
    seg = [x - m for x in seg]
    f = _estimate_freq(seg)
    z = [x * cmath.exp(-2j * math.pi * f * n) for n, x in enumerate(seg)]
    z = [sum(z[max(0, i - 3):i + 4]) / len(z[max(0, i - 3):i + 4]) for i in range(len(z))]
    ref_len = int(4 * ETU_SAMPLES)
    ref = sum(z[:ref_len])
    ref = ref / (abs(ref) or 1)
    soft = [(v * ref.conjugate()).real for v in z]

    # SOF: first stretch of >= 8 etu at logic 0
    i, sof = ref_len, None
    while i < len(soft) - int(10 * ETU_SAMPLES):
        if soft[i] < 0:
            j = i
            while j < len(soft) and soft[j] < 0:
                j += 1
            if j - i >= 8 * ETU_SAMPLES:
                sof = i
                break
            i = j
        i += 1
    if sof is None:
        return None
    j = sof
    while j < len(soft) and soft[j] < 0:
        j += 1
    k = j
    while k < len(soft) and soft[k] > 0:
        k += 1

    data, pos = [], k
    while pos + 10 * ETU_SAMPLES <= len(soft):
        bits = []
        for nbit in range(10):
            c = int(pos + (nbit + 0.5) * ETU_SAMPLES)
            bits.append(1 if sum(soft[c - 2:c + 3]) > 0 else 0)
        if bits[0] != 0 or bits[9] != 1:
            break
        data.append(sum(bits[1 + n] << n for n in range(8)))
        q = int(pos + 10 * ETU_SAMPLES) - 2
        while q < len(soft) and soft[q] > 0:
            q += 1
        pos = q
    return bytes(data)


class SoftST25TB:
    """ST25TB / SRIX protocol over the software ISO14443-B channel."""

    def __init__(self, cmd, tries=6):
        self.cmd = cmd
        self.tries = tries
        self.mod = ST25TB_MOD

    def xfer(self, payload, n_samples, expect_len, reset=False, tries=None):
        frame = bytes(payload) + crc_14b(bytes(payload))
        for _ in range(tries or self.tries):
            r = self.cmd.hf14b_bitbang(frame, etu_q8=ETU_Q8, rx_mode=2, n_samples=n_samples, sample_reg=0x3B,
                                       timeout_ms=3, reset_field=reset, keep_field=True, **self.mod)
            reset = False
            if r["spi_check"][0] != 0x92:
                raise RuntimeError(f"RC522 SPI desync after burst: {r['spi_check']}")
            for thr in (1.5, 1.0):          # lower threshold for weaker (farther) answers
                for ch in ("Q", "I"):
                    data = bpsk_decode(r["samples"], ch, thr=thr)
                    if data and crc_ok(data) and len(data) == expect_len:
                        return data[:-2]
        return None

    def initiate(self, attempts=3):
        """INITIATE with automatic modulation search; the working setting is kept for the session."""
        for mod in MOD_CANDIDATES:
            self.mod = mod
            resp = self.xfer([0x06, 0x00], 900, 3, reset=True, tries=attempts)
            if resp:
                return resp[0]
        self.mod = ST25TB_MOD
        return None

    def mod_str(self):
        names = {0x28: "CWGsPReg", 0x27: "GsNReg", 0x14: "TxControlReg"}
        return f"{names.get(self.mod['mod_reg'], hex(self.mod['mod_reg']))} 0x{self.mod['hi']:02X}/0x{self.mod['lo']:02X}"

    def select(self, chip_id):
        resp = self.xfer([0x0E, chip_id], 900, 3)
        return resp is not None and resp[0] == chip_id

    def get_uid(self):
        resp = self.xfer([0x0B], 1500, 10)
        return resp[::-1] if resp else None     # sent LSB first

    def read_block(self, block):
        return self.xfer([0x08, block], 1100, 6)

    def write_block(self, block, data, verify=True, tries=3):
        """
        WRITE_BLOCK (0x09). The tag does not answer, so the result is checked by
        reading the block back. Returns True when the block holds `data`.

        Note: blocks 0..4 are OTP (bits can only go 1 -> 0), 5..6 are count-down
        counters and 255 holds the OTP lock bits; writes there are irreversible.
        """
        data = bytes(data)
        if len(data) != 4:
            raise ValueError("ST25TB blocks are 4 bytes")
        payload = bytes([0x09, block]) + data
        frame = payload + crc_14b(payload)
        for _ in range(tries):
            self.cmd.hf14b_bitbang(frame, etu_q8=ETU_Q8, rx_mode=0, reset_field=False, keep_field=True,
                                   **self.mod)
            time.sleep(0.01)  # EEPROM programming time (tW ~ 5 ms)
            if not verify:
                return True
            if self.read_block(block) == data:
                return True
        return False

    def completion(self):
        frame = b"\x0f" + crc_14b(b"\x0f")
        self.cmd.hf14b_bitbang(frame, etu_q8=ETU_Q8, rx_mode=0, reset_field=False, keep_field=False,
                               **self.mod)


# Blocks whose writes are irreversible on ST25TB: OTP (0..4), count-down counters (5..6), system/lock (255)
PROTECTED_BLOCKS = set(range(0, 7)) | {0xFF}


def dump_to_blocks(dump: bytes):
    """Split a raw dump (blocks 0..N-1, 4 bytes each, as stored on the tag) into a list of blocks."""
    if len(dump) % 4:
        raise ValueError(f"dump size {len(dump)} is not a multiple of 4")
    return [bytes(dump[i:i + 4]) for i in range(0, len(dump), 4)]


def read_blocks(tag, count, progress=None):
    """Read blocks 0..count-1. Returns a list (None for blocks that could not be read)."""
    out = []
    for blk in range(count):
        data = tag.read_block(blk)
        out.append(data)
        if progress:
            progress(blk, data)
    return out


def diff_blocks(current, reference):
    """[(block, current, reference)] for blocks that differ (unreadable blocks count as different)."""
    return [(i, c, r) for i, (c, r) in enumerate(zip(current, reference)) if c != r]


def restore_blocks(tag, reference, force=False, progress=None):
    """
    Write `reference` blocks that differ from the tag, verifying each write.
    Protected blocks are skipped unless force=True. Returns (written, skipped, failed) block lists.
    """
    written, skipped, failed = [], [], []
    for blk, ref in enumerate(reference):
        cur = tag.read_block(blk)
        if cur == ref:
            continue
        if blk in PROTECTED_BLOCKS and not force:
            skipped.append(blk)
            continue
        ok = tag.write_block(blk, ref)
        (written if ok else failed).append(blk)
        if progress:
            progress(blk, cur, ref, ok)
    return written, skipped, failed
