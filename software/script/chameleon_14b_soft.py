"""
Experimental software ISO14443-B reader for the Chameleon Ultra.

The Ultra's RC522-compatible front-end (Ci522) has no ISO14443-B framing. This
module works around it entirely in software, on top of the experimental
HF14B_BITBANG firmware command:

* TX: the PCD->PICC frame (SOF, 10-bit characters, EOF, NRZ-L, ~10% ASK) is
  generated by rewriting CWGsPReg once per SPI byte in a single DMA burst.
* RX: the RC522 receiver cannot decode BPSK, but its TestADCReg exposes the
  I/Q ADC. Sampled at ~1 MS/s, the 847.5 kHz subcarrier aliases to ~150 kHz;
  we estimate that frequency (squaring removes the BPSK), mix down, low-pass,
  take the phase against TR1 (logic 1), find SOF and slice bits at 1 etu.
  Every frame is accepted only if its CRC_B is valid.
"""
import cmath
import math

US_PER_SAMPLE = 1.0025                      # measured SPIM byte period on nRF52840 @ 8 MHz
ETU_SAMPLES = 128 / 13.56 / US_PER_SAMPLE   # ~9.42 samples per etu
ETU_Q8 = round(ETU_SAMPLES * 256)
ST25TB_MOD = dict(mod_reg=0x28, hi=0x3F, lo=0x09)   # CWGsPReg 0x3F -> 0x09 gives a usable ASK depth


def crc_14b(data) -> bytes:
    """CRC_B (ISO/IEC 13239, CRC-16/X-25), returned LSB first as sent on air."""
    crc = 0xFFFF
    for b in data:
        crc ^= b
        for _ in range(8):
            crc = (crc >> 1) ^ 0x8408 if crc & 1 else crc >> 1
    crc = ~crc & 0xFFFF
    return bytes([crc & 0xFF, crc >> 8])


def crc_ok(frame) -> bool:
    return len(frame) >= 3 and crc_14b(frame[:-2]) == frame[-2:]


def _sx(v):
    return v - 16 if v > 7 else v


def _channel(samples, ch):
    return [_sx(x >> 4) if ch == "I" else _sx(x & 15) for x in samples]


def _active_span(sig, thr=1.5, win=12):
    rms = []
    for i in range(len(sig)):
        seg = sig[max(0, i - win // 2):i + win // 2]
        m = sum(seg) / len(seg)
        rms.append(math.sqrt(sum((x - m) ** 2 for x in seg) / len(seg)))
    on = [i for i, r in enumerate(rms) if r > thr]
    return (on[0], on[-1]) if on else None


def _estimate_freq(seg):
    def score(f):
        return abs(sum((x * x) * cmath.exp(-2j * 2 * math.pi * f * n) for n, x in enumerate(seg)))

    best_f, best_s = 0.0, -1.0
    f = 0.10
    while f < 0.20:
        s = score(f)
        if s > best_s:
            best_f, best_s = f, s
        f += 0.0005
    for f in [best_f + k * 0.00002 for k in range(-25, 26)]:
        s = score(f)
        if s > best_s:
            best_f, best_s = f, s
    return best_f


def bpsk_decode(samples, ch="Q"):
    """Decode one ISO14443-B PICC frame from TestADCReg samples. Returns bytes (incl. CRC) or None."""
    sig = _channel(samples, ch)
    span = _active_span(sig)
    if span is None:
        return None
    a, b = span[0] + 2, span[1]
    seg = sig[a:b]
    if len(seg) < 20 * ETU_SAMPLES:
        return None
    m = sum(seg) / len(seg)
    seg = [x - m for x in seg]
    f = _estimate_freq(seg)
    z = [x * cmath.exp(-2j * math.pi * f * n) for n, x in enumerate(seg)]
    z = [sum(z[max(0, i - 3):i + 4]) / len(z[max(0, i - 3):i + 4]) for i in range(len(z))]
    ref_len = int(4 * ETU_SAMPLES)
    ref = sum(z[:ref_len])
    ref = ref / (abs(ref) or 1)
    soft = [(v * ref.conjugate()).real for v in z]

    # SOF: first stretch of >= 8 etu at logic 0
    i, sof = ref_len, None
    while i < len(soft) - int(10 * ETU_SAMPLES):
        if soft[i] < 0:
            j = i
            while j < len(soft) and soft[j] < 0:
                j += 1
            if j - i >= 8 * ETU_SAMPLES:
                sof = i
                break
            i = j
        i += 1
    if sof is None:
        return None
    j = sof
    while j < len(soft) and soft[j] < 0:
        j += 1
    k = j
    while k < len(soft) and soft[k] > 0:
        k += 1

    data, pos = [], k
    while pos + 10 * ETU_SAMPLES <= len(soft):
        bits = []
        for nbit in range(10):
            c = int(pos + (nbit + 0.5) * ETU_SAMPLES)
            bits.append(1 if sum(soft[c - 2:c + 3]) > 0 else 0)
        if bits[0] != 0 or bits[9] != 1:
            break
        data.append(sum(bits[1 + n] << n for n in range(8)))
        q = int(pos + 10 * ETU_SAMPLES) - 2
        while q < len(soft) and soft[q] > 0:
            q += 1
        pos = q
    return bytes(data)


class SoftST25TB:
    """ST25TB / SRIX protocol over the software ISO14443-B channel."""

    def __init__(self, cmd, tries=6):
        self.cmd = cmd
        self.tries = tries

    def xfer(self, payload, n_samples, expect_len, reset=False):
        frame = bytes(payload) + crc_14b(bytes(payload))
        for _ in range(self.tries):
            r = self.cmd.hf14b_bitbang(frame, etu_q8=ETU_Q8, rx_mode=2, n_samples=n_samples, sample_reg=0x3B,
                                       timeout_ms=3, reset_field=reset, keep_field=True, **ST25TB_MOD)
            reset = False
            if r["spi_check"][0] != 0x92:
                raise RuntimeError(f"RC522 SPI desync after burst: {r['spi_check']}")
            for ch in ("Q", "I"):
                data = bpsk_decode(r["samples"], ch)
                if data and crc_ok(data) and len(data) == expect_len:
                    return data[:-2]
        return None

    def initiate(self, attempts=10):
        for _ in range(attempts):
            resp = self.xfer([0x06, 0x00], 900, 3, reset=True)
            if resp:
                return resp[0]
        return None

    def select(self, chip_id):
        resp = self.xfer([0x0E, chip_id], 900, 3)
        return resp is not None and resp[0] == chip_id

    def get_uid(self):
        resp = self.xfer([0x0B], 1500, 10)
        return resp[::-1] if resp else None     # sent LSB first

    def read_block(self, block):
        return self.xfer([0x08, block], 1100, 6)

    def completion(self):
        frame = b"\x0f" + crc_14b(b"\x0f")
        self.cmd.hf14b_bitbang(frame, etu_q8=ETU_Q8, rx_mode=0, reset_field=False, keep_field=False,
                               **ST25TB_MOD)
